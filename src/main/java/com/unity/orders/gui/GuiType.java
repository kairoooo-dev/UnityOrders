package com.unity.orders.gui;

/**
 * Enumerates all GUI types used by the marketplace.
 */
public enum GuiType {
    /** The main marketplace menu. */
    MAIN,
    /** The player's own orders list. */
    MY_ORDERS,
    /** The browse-all-orders list. */
    BROWSE,
    /** The create-order input GUI. */
    CREATE_ORDER,
    /** The order detail view. */
    ORDER_DETAIL
}
